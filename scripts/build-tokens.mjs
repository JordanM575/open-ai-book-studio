#!/usr/bin/env node
/**
 * Turns design/tokens.json (the Liquid Glass token file from the design kit) into the CSS custom
 * properties the renderer uses. Run `pnpm tokens` after changing the design tokens; the generated
 * file is committed so a build never depends on the design kit being present.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const here = dirname(new URL(import.meta.url).pathname);
const root = resolve(here, "..");
const tokensPath = resolve(root, "design/tokens.json");
const outPath = resolve(root, "packages/ui/src/styles/tokens.generated.css");

const tokens = JSON.parse(await readFile(tokensPath, "utf8"));
const byName = new Map(tokens.color.tokens.map((token) => [token.name, token.value]));

/** Resolves `{primitive}` chains for one theme. Semantic tokens may point at other semantics. */
function resolveToken(name, theme, seen = []) {
  if (seen.includes(name)) throw new Error(`Circular token reference: ${[...seen, name].join(" -> ")}`);
  if (!byName.has(name)) throw new Error(`Token references unknown token: ${name}`);
  const raw = byName.get(name);
  const literal = typeof raw === "string" ? raw : raw?.[theme];
  if (typeof literal !== "string") return undefined;
  const reference = /^\{([^}]+)\}$/.exec(literal.trim());
  return reference ? resolveToken(reference[1], theme, [...seen, name]) : literal;
}

const primitiveEntries = [];
const semantic = [];

for (const token of tokens.color.tokens) {
  const raw = token.value;
  const isPrimitive = typeof raw === "string" && raw.startsWith("#");
  if (isPrimitive) {
    primitiveEntries.push([token.name, raw]);
    continue;
  }
  const light = resolveToken(token.name, "light");
  const dark = resolveToken(token.name, "dark");
  if (!light) throw new Error(`Token ${token.name} has no light value`);
  semantic.push({ name: token.name, light, ...(dark && dark !== light ? { dark } : {}) });
}

const lines = [];
lines.push("/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */");
lines.push(`/* Source: ${tokens.name} v${tokens.version}. */`);
lines.push("");
lines.push(":root {");
lines.push("  color-scheme: light;");
lines.push("");
lines.push("  /* primitives */");
for (const [name, value] of primitiveEntries) lines.push(`  --${name}: ${value};`);
lines.push("");
lines.push("  /* semantic colours */");
for (const token of semantic) lines.push(`  --${token.name}: ${token.light};`);
lines.push("");
lines.push("  /* type families */");
for (const [name, value] of Object.entries(tokens.type.families)) lines.push(`  --font-${name}: ${value};`);
lines.push("");
lines.push("  /* type scale */");
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    lines.push(`  --text-${style.name}-size: ${style.fontSize};`);
    lines.push(`  --text-${style.name}-leading: ${style.lineHeight};`);
    lines.push(`  --text-${style.name}-weight: ${style.fontWeight};`);
    if (style.letterSpacing) lines.push(`  --text-${style.name}-tracking: ${style.letterSpacing};`);
  }
}
lines.push("");
lines.push("  /* spacing, radius, size, motion */");
for (const token of tokens.spacing.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.radius.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.size.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.duration.tokens) lines.push(`  --${token.name}: ${token.value};`);
for (const token of tokens.breakpoint.tokens) lines.push(`  --${token.name}: ${token.value};`);
lines.push("");
lines.push("  /* elevation */");
for (const token of tokens.shadow.tokens) {
  const value = typeof token.value === "string" ? token.value : token.value.light;
  lines.push(`  --${token.name}: ${value};`);
}
lines.push("}");

const darkTokens = semantic.filter((token) => token.dark);
if (darkTokens.length > 0) {
  lines.push("");
  lines.push('[data-theme="dark"] {');
  lines.push("  color-scheme: dark;");
  for (const token of darkTokens) lines.push(`  --${token.name}: ${token.dark};`);
  for (const token of tokens.shadow.tokens) {
    if (typeof token.value === "string") continue;
    lines.push(`  --${token.name}: ${token.value.dark};`);
  }
  lines.push("}");
}

lines.push("");
lines.push("/* Bridge the semantic tokens into Tailwind utilities (bg-background, text-primary, …). */");
lines.push("@theme inline {");
for (const token of semantic) lines.push(`  --color-${token.name}: var(--${token.name});`);
lines.push("  --font-sans: var(--font-ui);");
lines.push("  --font-serif: var(--font-reading);");
lines.push("  --font-mono: var(--font-code);");
for (const token of tokens.radius.tokens) lines.push(`  --radius-${token.name.replace(/^corner-/, "")}: var(--${token.name});`);
lines.push("}");
lines.push("");

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${semantic.length} semantic colours and ${primitiveEntries.length} primitives to ${outPath}`);
